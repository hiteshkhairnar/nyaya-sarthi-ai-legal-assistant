import { useState } from "react";
import { AppLayout } from "@/components/AppLayout";
import { downloadDraftAsDocx } from "@/lib/docxExport";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { PenTool, Loader2, Copy, Download, CheckCircle2 } from "lucide-react";
import { toast } from "sonner";

const docTypes = [
  "Legal Notice (Section 80 CPC)",
  "Affidavit",
  "Bail Application",
  "Writ Petition",
  "Rent Agreement",
  "Power of Attorney",
  "Partnership Deed",
  "Non-Disclosure Agreement",
  "Employment Agreement",
  "Cease & Desist Notice",
  "Reply to Legal Notice",
  "Consumer Complaint",
];

export default function DraftGeneratorPage() {
  const [docType, setDocType] = useState("");
  const [parties, setParties] = useState("");
  const [details, setDetails] = useState("");
  const [draft, setDraft] = useState("");
  const [isLoading, setIsLoading] = useState(false);

  const handleGenerate = () => {
    if (!docType) return;
    setIsLoading(true);
    setTimeout(() => {
      setDraft(
        `# ${docType}\n\n**Date:** 23rd March, 2026\n**Place:** New Delhi\n\n---\n\nBEFORE THE HON'BLE COURT OF ____________\n\nIN THE MATTER OF:\n\n**${parties || "[Name of Party A]"}** …Petitioner/Applicant\n\nVERSUS\n\n**[Name of Party B]** …Respondent/Opposite Party\n\n---\n\n## RESPECTFULLY SHOWETH:\n\n1. That the Petitioner is a law-abiding citizen of India and is filing this ${docType} under the provisions of the applicable Indian statute.\n\n2. That the facts and circumstances leading to the filing of this document are as follows:\n\n   a) The Petitioner and the Respondent entered into a legal relationship governed by the laws of India.\n   \n   b) The Respondent has acted in contravention of the terms agreed upon and the provisions of the applicable Act.\n\n3. That the Petitioner has made sincere efforts to resolve the matter amicably but the Respondent has failed to respond.\n\n## PRAYER\n\nIn light of the above facts and circumstances, it is most respectfully prayed that this Hon'ble Court may be pleased to:\n\na) Grant appropriate relief as prayed for;\n\nb) Award costs of the proceedings;\n\nc) Pass such other and further orders as this Hon'ble Court may deem fit and proper in the interest of justice.\n\n## VERIFICATION\n\nI, ${parties || "[Name]"}, the Petitioner above named, do hereby verify that the contents of the above are true and correct to the best of my knowledge and belief and nothing material has been concealed therefrom.\n\nVerified at New Delhi on this 23rd day of March, 2026.\n\n_________________________\nPetitioner / Deponent\n\nThrough:\nAdv. [Name of Advocate]\nBar Council Enrolment No.: ___________\n\n---\n*This document was generated by Nyaya Sarthi AI and should be reviewed by a licensed advocate before filing. This does not constitute legal advice under the Advocates Act, 1961.*`
      );
      setIsLoading(false);
    }, 2000);
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(draft);
    toast.success("Draft copied to clipboard");
  };

  return (
    <AppLayout>
      <div className="max-w-5xl mx-auto space-y-8">
        <div className="animate-fade-up">
          <h1 className="text-2xl font-serif font-bold tracking-tight">Legal Draft Generator</h1>
          <p className="text-sm text-muted-foreground mt-1">
            Generate legal notices, petitions, agreements, and affidavits with AI.
          </p>
        </div>

        <div className="grid grid-cols-1 lg:grid-cols-5 gap-6 animate-fade-up stagger-1">
          <div className="lg:col-span-2 space-y-5">
            <div className="surface-elevated rounded-xl p-6 space-y-5">
              <div>
                <Label className="text-sm font-medium">Document Type</Label>
                <Select value={docType} onValueChange={setDocType}>
                  <SelectTrigger className="mt-1.5">
                    <SelectValue placeholder="Select document type" />
                  </SelectTrigger>
                  <SelectContent>
                    {docTypes.map((t) => (
                      <SelectItem key={t} value={t}>{t}</SelectItem>
                    ))}
                  </SelectContent>
                </Select>
              </div>

              <div>
                <Label className="text-sm font-medium">Parties Involved</Label>
                <Input
                  value={parties}
                  onChange={(e) => setParties(e.target.value)}
                  placeholder="e.g., Rajesh Kumar & Priya Enterprises Pvt. Ltd."
                  className="mt-1.5"
                />
              </div>

              <div>
                <Label className="text-sm font-medium">Additional Details</Label>
                <Textarea
                  value={details}
                  onChange={(e) => setDetails(e.target.value)}
                  placeholder="Describe key terms, jurisdiction, relevant sections of law..."
                  className="mt-1.5 min-h-[120px]"
                />
              </div>

              <Button onClick={handleGenerate} disabled={isLoading || !docType} className="w-full">
                {isLoading ? (
                  <>
                    <Loader2 className="mr-2 h-4 w-4 animate-spin" />
                    Generating...
                  </>
                ) : (
                  <>
                    <PenTool className="mr-2 h-4 w-4" />
                    Generate Draft
                  </>
                )}
              </Button>
            </div>
          </div>

          <div className="lg:col-span-3 surface-elevated rounded-xl p-6 min-h-[500px]">
            {!draft && !isLoading && (
              <div className="flex flex-col items-center justify-center h-full text-center text-muted-foreground">
                <PenTool className="h-10 w-10 mb-3 opacity-40" />
                <p className="text-sm">Your generated document will appear here</p>
              </div>
            )}
            {isLoading && (
              <div className="flex flex-col items-center justify-center h-full">
                <Loader2 className="h-8 w-8 animate-spin text-primary mb-3" />
                <p className="text-sm text-muted-foreground">Drafting document...</p>
              </div>
            )}
            {draft && !isLoading && (
              <div className="animate-fade-up">
                <div className="flex items-center justify-between mb-4">
                  <div className="flex items-center gap-2">
                    <CheckCircle2 className="h-4 w-4 text-emerald-500" />
                    <span className="text-sm font-medium">Draft Ready</span>
                  </div>
                  <div className="flex gap-2">
                    <Button variant="outline" size="sm" onClick={handleCopy}>
                      <Copy className="mr-1.5 h-3.5 w-3.5" />
                      Copy
                    </Button>
                    <Button variant="outline" size="sm" onClick={() => downloadDraftAsDocx({ docType, parties, draftText: draft })}>
                      <Download className="mr-1.5 h-3.5 w-3.5" />
                      Download DOCX
                    </Button>
                  </div>
                </div>
                <div className="prose prose-sm max-w-none text-sm leading-relaxed whitespace-pre-wrap border-t border-border pt-4">
                  {draft}
                </div>
              </div>
            )}
          </div>
        </div>
      </div>
    </AppLayout>
  );
}
